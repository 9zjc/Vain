run(function()
	local Sprint
	local old
	
	Sprint = vape.Categories.Combat:CreateModule({
		Name = 'Sprint',
		Function = function(callback)
			if callback then
				if inputService.TouchEnabled then pcall(function() lplr.PlayerGui.MobileUI['2'].Visible = false end) end
				old = bedwars.SprintController.stopSprinting
				bedwars.SprintController.stopSprinting = function(...)
					local call = old(...)
					bedwars.SprintController:startSprinting()
					return call
				end
				Sprint:Clean(entitylib.Events.LocalAdded:Connect(function() bedwars.SprintController:stopSprinting() end))
				bedwars.SprintController:stopSprinting()
			else
				if inputService.TouchEnabled then pcall(function() lplr.PlayerGui.MobileUI['2'].Visible = true end) end
				bedwars.SprintController.stopSprinting = old
				bedwars.SprintController:stopSprinting()
			end
		end,
		Tooltip = 'Sets your sprinting to true.'
	})
end)

run(function()
	local AutoVote
	local Choice
	local voted = false
	
	local function activate(button)
	if firesignal then
	pcall(firesignal, button.MouseButton1Click)
	elseif button.Activate then
	pcall(button.Activate, button)
	end
	end
	
	local function vote()
	if voted then return end
	local buttons = {}
	for _, obj in lplr.PlayerGui:GetDescendants() do
	if (obj:IsA('TextButton') or obj:IsA('ImageButton')) and obj.Visible then
	local name = (obj.Name..' '..(obj:IsA('TextButton') and obj.Text or '')..' '..obj.Parent.Name):lower()
	if name:find('vote') or name:find('map') then
	table.insert(buttons, obj)
	end
	end
	end
	table.sort(buttons, function(a, b)
	return a.AbsolutePosition.X < b.AbsolutePosition.X
	end)
	if #buttons == 0 then return end
	local button = buttons[math.clamp(Choice.Value, 1, #buttons)]
	if button then
	activate(button)
	voted = true
	end
	end
	
	AutoVote = vape.Categories.Utility:CreateModule({
	Name = 'AutoVote',
	Function = function(callback)
	voted = false
	if callback then
	AutoVote:Clean(lplr.PlayerGui.DescendantAdded:Connect(function()
	task.delay(0.1, vote)
	end))
	task.spawn(function()
	repeat
	vote()
	task.wait(0.25)
	until voted or not AutoVote.Enabled
	end)
	end
	end,
	Tooltip = 'Votes for the selected visible map as soon as voting opens'
	})
	
	Choice = AutoVote:CreateSlider({
	Name = 'Map slot',
	Min = 1,
	Max = 3,
	Default = 1
	})
end)

run(function()
	local AutoGamble
	
	AutoGamble = vape.Categories.World:CreateModule({
		Name = 'AutoGamble',
		Function = function(callback)
			if callback then
				AutoGamble:Clean(bedwars.Client:GetNamespace('RewardCrate'):Get('CrateOpened'):Connect(function(data)
					if data.openingPlayer == lplr then
						local tab = bedwars.CrateItemMeta[data.reward.itemType] or {displayName = data.reward.itemType or 'unknown'}
						notif('AutoGamble', 'Won '..tab.displayName, 5)
					end
				end))
	
				repeat
					if not bedwars.CrateAltarController.activeCrates[1] then
						for _, v in bedwars.Store:getState().Consumable.inventory do
							if v.consumable:find('crate') then
								bedwars.CrateAltarController:pickCrate(v.consumable, 1)
								task.wait(1.2)
								if bedwars.CrateAltarController.activeCrates[1] and bedwars.CrateAltarController.activeCrates[1][2] then
									bedwars.Client:GetNamespace('RewardCrate'):Get('OpenRewardCrate'):SendToServer({
										crateId = bedwars.CrateAltarController.activeCrates[1][2].attributes.crateId
									})
								end
								break
							end
						end
					end
					task.wait(1)
				until not AutoGamble.Enabled
			end
		end,
		Tooltip = 'Automatically opens lucky crates, piston inspired!'
	})
end)